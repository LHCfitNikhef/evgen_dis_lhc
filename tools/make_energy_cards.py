def powheg_v2_card(b):
    """POWHEG-V2 wants a SYMMETRIC c.m. pair, not the fixed-target form."""
    src = os.path.join(REPO, "powheg", "cards", "POWHEG-V2", "nu1TeV-prod",
                       "powheg.input")
    text = open(src).read()
    e = b.powheg_v2_ebeam
    for key in ("ebeam1", "ebeam2"):
        old_e = f"{key} 21.66462758937933d0"
        assert old_e in text, f"the POWHEG-V2 template no longer sets {old_e!r}"
        text = text.replace(old_e, f"{key} {e:.11f}d0")
    return ("! GENERATED by tools/make_energy_cards.py from nu1TeV-prod"
            " -- edit that one.\n") + text


def main():
    changed = 0
    if EXTRA is not None:
        b = beams.Beams("nu", EXTRA)
        print(f"off-scan comparison point {EXTRA:g} GeV [{b.tag}], "
              "POWHEG-V2 neutrino only:")
        changed += write(os.path.join(REPO, "powheg", "cards", "POWHEG-V2",
                                      f"nu{b.tag}-prod", "powheg.input"),
                         powheg_v2_card(b))
        print(f"\n{changed} card(s) {'would change' if CHECK else 'written'}.")
        return
    print("Pythia 8 cards:")
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue                      # the template; never regenerated
        b = beams.Beams("mu", e)
        changed += write(
            os.path.join(REPO, "pythia8", f"dis_mu{b.tag}.cmnd"), pythia_card(b))

    print("Sherpa LO cards:")
    runner = open(os.path.join(REPO, "sherpa", "Runs", "MuonDIS_LO",
                               "run_parallel.sh")).read()
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue
        b = beams.Beams("mu", e)
        d = os.path.join(REPO, "sherpa", "Runs", f"MuonDIS_LO_{b.tag}")
        changed += write(os.path.join(d, "Sherpa.yaml"), sherpa_card(b))
        # the parallel-run script is energy-independent; copied rather than
        # shared so link_cards.sh installs one per run dir, as it does for
        # every other Sherpa run
        changed += write(os.path.join(d, "run_parallel.sh"), runner)
        os.chmod(os.path.join(d, "run_parallel.sh"), 0o755)

    print("Herwig LO cards:")
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue
        b = beams.Beams("mu", e)
        changed += write(
            os.path.join(REPO, "herwig7", f"DIS-mu-{b.tag}.in"), herwig_card(b))

    print("POWHEG-RES cards:")
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue
        b = beams.Beams("mu", e)
        changed += write(
            os.path.join(REPO, "powheg", "cards", "POWHEG-RES",
                         f"mu{b.tag}-wide", "powheg.input"), powheg_res_card(b))

    print("Sherpa MC@NLO cards (MUON only -- see sherpa_nlo_card):")
    nlo_runner = open(os.path.join(REPO, "sherpa", "Runs", "MuonDIS_NLO",
                                   "run_parallel.sh")).read()
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue
        b = beams.Beams("mu", e)
        d = os.path.join(REPO, "sherpa", "Runs", f"MuonDIS_NLO_{b.tag}")
        changed += write(os.path.join(d, "Sherpa.yaml"), sherpa_nlo_card(b))
        changed += write(os.path.join(d, "run_parallel.sh"), nlo_runner)
        os.chmod(os.path.join(d, "run_parallel.sh"), 0o755)

    print("Herwig POWHEG-matched NLO cards (both currents, both halves):")
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue
        for src, stem, cur in HERWIG_PWG_CARDS:
            b = beams.Beams(cur, e)
            changed += write(
                os.path.join(REPO, "herwig7", f"{stem}-{b.tag}.in"),
                herwig_pwg_card(b, src, stem))

    print("Neutrino cards (Pythia / Herwig / Sherpa LO / POWHEG-V2):")
    nu_runner = open(os.path.join(REPO, "sherpa", "Runs", "NuDIS_LO",
                                  "run_parallel.sh")).read()
    for e in beams.ENERGIES:
        if e == beams.ANCHOR_ENERGY:
            continue
        b = beams.Beams("nu", e)
        changed += write(os.path.join(REPO, "pythia8", f"dis_nu{b.tag}.cmnd"),
                         pythia_nu_card(b))
        changed += write(
            os.path.join(REPO, "herwig7", f"DIS-nu-POL-{b.tag}.in"),
            herwig_nu_card(b))
        d = os.path.join(REPO, "sherpa", "Runs", f"NuDIS_LO_{b.tag}")
        changed += write(os.path.join(d, "Sherpa.yaml"), sherpa_nu_card(b))
        changed += write(os.path.join(d, "run_parallel.sh"), nu_runner)
        os.chmod(os.path.join(d, "run_parallel.sh"), 0o755)
        changed += write(os.path.join(REPO, "powheg", "cards", "POWHEG-V2",
                                      f"nu{b.tag}-prod", "powheg.input"),
                         powheg_v2_card(b))

    print(f"\n{changed} card(s) {'would change' if CHECK else 'written'}.")
    if not CHECK and changed:
        print("Sherpa run dirs are new: run ./tools/link_cards.sh to symlink\n"
              "them into the install tree, then integrate before generating.")


if __name__ == "__main__":
    main()
