def herwig_nu_card(b):
    """From DIS-nu-POL.in, the POLARIZED card -- NOT DIS-nu.in.

    This matters by a factor of two.  DIS-nu.in leaves the neutrino beam
    unpolarised, so Herwig spin-averages over two incoming helicities when a
    massless neutrino has only one, and the cross-section comes out HALVED.
    DIS-nu-POL.in declares the beam as PolarizedBeamParticleData with
    LongitudinalPolarization = -1, which is why analyze_nu.py carries
    HERWIG_NU_SPIN_FACTOR = 1.0 and why the published 1 TeV sample lives in
    nu_job_*/DIS-nu-POL-S*.out.

    Generating from DIS-nu.in put Herwig at exactly ratio 0.5 to YADISM at
    400 GeV and 4 TeV while 1 TeV sat on 1.0 -- visible the moment the
    neutrino panel of cmp_sigma_vs_E was drawn.
    """
    src = os.path.join(REPO, "herwig7", "DIS-nu-POL.in")
    text = open(src).read()
    ea, eb = b.cm_energies
    # saverun names the OUTPUT; leaving it would clobber the 1 TeV run file
    old_save = "saverun DIS-nu-POL EventGenerator"
    assert old_save in text, "DIS-nu-POL.in no longer ends with saverun DIS-nu-POL"
    text = text.replace(old_save, f"saverun DIS-nu-POL-{b.tag} EventGenerator")
    for old_e, new_e in (("set Luminosity:BeamEMaxA 21.654469*GeV",
                          f"set Luminosity:BeamEMaxA {ea:.6f}*GeV"),
                         ("set Luminosity:BeamEMaxB 21.674786*GeV",
                          f"set Luminosity:BeamEMaxB {eb:.6f}*GeV")):
        assert old_e in text, f"DIS-nu.in no longer sets {old_e!r}"
        text = text.replace(old_e, new_e)
    return ("# GENERATED by tools/make_energy_cards.py from DIS-nu.in"
            " -- edit that one.\n") + text


